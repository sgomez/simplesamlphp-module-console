import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { _ } from 'ajv/dist/compile/codegen/index.js';
import { compile } from 'json-schema-to-typescript';
import { formats } from '../src/domain/documents/formats.ts';
import { declareKeywords } from './keywords.ts';
import { rewrite, split } from './opis.ts';

const ROOT = join(import.meta.dirname, '../..');
const SCHEMAS = join(ROOT, 'docs/spec/schemas');
const OUT = join(ROOT, 'frontend/src/domain/documents/generated');
const BASE = 'https://console.invalid/schemas/';
const BANNER = '// Generated by npm run generate from docs/spec/schemas. Do not edit.\n';

const files = (dir) =>
  readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => (entry.isDirectory() ? files(join(dir, entry.name)) : [join(dir, entry.name)]))
    .filter((file) => file.endsWith('.json'))
    .sort();

const schemas = files(SCHEMAS).map((file) => {
  const path = relative(SCHEMAS, file).split('\\').join('/');
  const schema = JSON.parse(readFileSync(file, 'utf8'));
  const parts = path.replace(/\.json$/, '').split('/');
  const set = parts[0] === 'entities' ? parts[1] : `${parts[1]}:${parts[2]}`;

  return { file, path, schema, set, document: schema.type === 'object' };
});
const documents = schemas.filter((s) => s.document);
const identifier = (set) => set.replace(/[^A-Za-z0-9]+(.)/g, (_m, c) => c.toUpperCase()).replace(/^./, (c) => c.toLowerCase());
const typeName = (set) => identifier(set).replace(/^./, (c) => c.toUpperCase());

function validators() {
  const ajv = new Ajv2020({
    allErrors: true,
    inlineRefs: false,
    verbose: true,
    strictTypes: false,
    strictTuples: false,
    formats,
    code: { source: true, esm: true, formats: _`formats` },
  });
  declareKeywords(ajv);
  for (const { path, schema } of schemas) {
    ajv.addSchema(rewrite(split(schema)), BASE + path);
  }
  const code = standaloneCode(ajv, Object.fromEntries(documents.map((d) => [identifier(d.set), BASE + d.path])))
    .replace(/^"use strict";/, '')
    .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length')
    .replaceAll('require("ajv/dist/runtime/equal").default', 'equal');
  if (code.includes('require(')) {
    throw new Error('The validators need an Ajv runtime helper the front end does not provide');
  }
  const map = documents.map((d) => `  ${JSON.stringify(d.set)}: ${identifier(d.set)},`).join('\n');
  const imports = "import { formats } from '../formats';\nimport { equal, ucs2length } from '../runtime';\n";

  return `${BANNER}${imports}${code}\nexport const validators = {\n${map}\n};\n`;
}

function declarations() {
  const sets = documents.map((d) => `  | ${JSON.stringify(d.set)}`).join('\n');

  return `${BANNER}import type { ValidateFunction } from 'ajv/dist/2020';

export type DocumentSet =
${sets};

export const validators: Record<DocumentSet, ValidateFunction>;
`;
}

const byPath = new Map(schemas.map((s) => [s.path, s.schema]));

// Types are generated from the document with every reference inlined and no titles, so that each
// document gives one interface and nothing else.
function inline(node, path) {
  if (Array.isArray(node)) {
    return node.map((item) => inline(item, path));
  }
  if (node === null || typeof node !== 'object') {
    return node;
  }
  const own = Object.fromEntries(
    Object.entries(node)
      .filter(([key]) => key !== 'title' && key !== '$ref' && key !== '$defs')
      .map(([key, value]) => [key, inline(value, path)]),
  );
  if (typeof node.$ref !== 'string') {
    return own;
  }
  const [file, pointer] = node.$ref.split('#');
  const target = file === '' ? path : join(dirname(path), file).split('\\').join('/');
  const found = pointer.split('/').slice(1).reduce((at, key) => at[key], byPath.get(target));

  return { ...inline(found, target), ...own };
}

async function types() {
  const out = [];
  for (const { path, schema, set } of documents) {
    out.push(
      await compile(inline(schema, path), typeName(set), {
        bannerComment: '',
        ignoreMinAndMaxItems: true,
        unreachableDefinitions: false,
      }),
    );
  }
  const map = documents.map((d) => `  ${JSON.stringify(d.set)}: ${typeName(d.set)};`).join('\n');

  return `${BANNER}${out.join('\n')}\nexport interface Documents {\n${map}\n}\n`;
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'validators.js'), validators());
writeFileSync(join(OUT, 'validators.d.ts'), declarations());
writeFileSync(join(OUT, 'documents.ts'), await types());
